  BookOpen:'book-2-linear', BookOpenCheck:'book-bookmark-linear', Bookmark:'bookmark-linear', Braces:'code-2-linear',
  Brain:'brain-linear', BrainCircuit:'cpu-bolt-linear', ChartNoAxesCombined:'graph-up-linear', Check:'check-linear',
