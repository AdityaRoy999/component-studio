  Smartphone:'smartphone-linear', Sparkles:'stars-linear', Square:'stop-linear', Star:'star-linear', Sun:'sun-linear',
  Tablet:'tablet-linear', Terminal:'code-square-linear', ThumbsUp:'like-linear', Trash2:'trash-bin-trash-linear',
