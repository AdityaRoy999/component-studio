  Code2:'code-linear', Command:'command-linear', Compass:'compass-linear', Copy:'copy-linear',
  Download:'download-minimalistic-linear', Eye:'eye-linear', EyeOff:'eye-closed-linear', FileCode2:'file-code-linear',
  FlaskConical:'test-tube-linear', Folder:'folder-linear', Gamepad2:'gamepad-linear', Gauge:'speedometer-middle-linear',
  Heart:'heart-linear', History:'history-linear', Home:'home-2-linear', Image:'gallery-linear', ImageIcon:'gallery-linear',
  ImagePlus:'gallery-add-linear', KeyRound:'key-minimalistic-linear', Laptop:'laptop-linear', Layers:'layers-linear',
  Layers3:'layers-minimalistic-linear', Loader2:'refresh-linear', Magnet:'magnet-linear', Maximize2:'full-screen-linear',
  Menu:'hamburger-menu-linear', Mic:'microphone-2-linear', Minimize2:'quit-full-screen-linear', Minus:'minus-linear', Moon:'moon-linear',
  MousePointer2:'cursor-linear', NotebookPen:'notebook-linear', Palette:'palette-linear', PanelTop:'window-frame-linear',
  Pencil:'pen-2-linear', Plus:'add-linear', RefreshCw:'refresh-linear', RotateCcw:'restart-linear', Search:'magnifier-linear',
